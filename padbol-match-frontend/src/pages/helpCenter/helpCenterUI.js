const CATEGORY_LABELS = {
  es: {account: 'Cuenta'},
  en: {account: 'Account'},
  pt: {account: 'Conta'},
};

export function categoryLabel(category, language) {
  const lang = normalizeHelpLanguage(language);
  return CATEGORY_LABELS[lang]?.[category] || String(category || '');
}

export function helpCopy(language) {
  return HELP_UI[normalizeHelpLanguage(language)] || HELP_UI.en;
}

export function articleCopy(article, language) {
  const lang = normalizeHelpLanguage(language);
  const translation = article?.translations?.[lang] || article?.translations?.es;
  return {
    title: translation?.title || '',
    purpose: translation?.purpose || '',
    steps: Array.isArray(translation?.steps) ? translation.steps : [],
    note: translation?.note || '',
    requirements: article?.requirements?.[lang] || article?.requirements?.es || [],
    issues: article?.commonIssues?.[lang] || article?.commonIssues?.es || [],
    visualFields: article?.visualFields?.[lang] || article?.visualFields?.es || [],
    audience: article?.audienceLabel?.[lang] || article?.audienceLabel?.es || '',
    scope: article?.verifiedScopeText?.[lang] || article?.verifiedScope || '',
    categoryLabel: categoryLabel(article?.category, lang),
  };
}
