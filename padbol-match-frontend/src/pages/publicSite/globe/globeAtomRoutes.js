function nodePair(from, to) {
  return {
    from,
    to,
    a: NI[from],
    b: NI[to],
    lonA: GLOBE_NODES[NI[from]].lon,
    latA: GLOBE_NODES[NI[from]].lat,
    lonB: GLOBE_NODES[NI[to]].lon,
    latB: GLOBE_NODES[NI[to]].lat,
  };
}

