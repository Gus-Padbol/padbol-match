export const GLOBE_STATIC_PACKETS = GLOBE_STATIC_LABELS.desktop;

export function altitudeAt(t, peak) {
  const x = Math.max(0, Math.min(1, t));
  return peak * Math.sin(Math.PI * x);
}

export function easeInOutCubic(t) {
  const x = Math.max(0, Math.min(1, t));
  return x < 0.5 ? 4 * x * x * x : 1 - ((-2 * x + 2) ** 3) / 2;
}

/** Gap corto: superposición temporal y menos ventanas vacías. */
export const PACKET_CYCLE_GAP_MS = 900;

export function packetProgress(elapsedMs, route) {
  const gap = PACKET_CYCLE_GAP_MS;
  const cycle = route.durationMs + gap;
  const local = ((elapsedMs - route.delayMs) % cycle + cycle) % cycle;
  if (local > route.durationMs) return null;
  const raw = local / route.durationMs;
  const t = route.reverse ? 1 - easeInOutCubic(raw) : easeInOutCubic(raw);
  const edge = Math.min(local / 1100, (route.durationMs - local) / 1100, 1);
  return { t, edge, local };
}
